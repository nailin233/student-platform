/**
 * 小程序 API 地址配置
 * ---------------------------------------------------------------------------
 * 三种运行环境的地址不同，集中在这里改，避免散落在各页面里：
 *
 *   1) 开发者工具（模拟器）
 *      用 localhost / 127.0.0.1 即可，请求由开发者工具转发到本机。
 *      注意：需要在开发者工具「详情 → 本地设置」勾选「不校验合法域名」。
 *
 *   2) 真机预览 / 真机调试
 *      手机和电脑不在同一个 loopback，必须填电脑在局域网里的 IP，
 *      例如 'http://192.168.1.8:8000'。后端要监听 0.0.0.0 而不是 127.0.0.1：
 *          uvicorn main:app --host 0.0.0.0 --port 8000
 *      同样需要勾选「不校验合法域名」。
 *
 *   3) 正式发布
 *      必须是已备案域名的 HTTPS 地址，如 'https://api.example.com'，
 *      且要在微信公众平台配置 request 合法域名。Demo 阶段不涉及。
 *
 * 当前默认值按「开发者工具」配置，切换到真机时只改下面这一行。
 */

const ENV = 'dev' // 'dev' 开发者工具 | 'lan' 真机局域网

const API_BASE = {
  dev: 'http://localhost:8000',
  // 换成你自己电脑的局域网 IP（ipconfig 查看），例如 http://192.168.1.8:8000
  lan: 'http://192.168.1.8:8000'
}

module.exports = {
  apiBase: API_BASE[ENV],
  env: ENV
}
